using System.Text;

namespace Poppler.Text;

internal static class PdfBase14Metrics
{
    private static readonly MetricsTable Courier = Parse(CourierData);
    private static readonly MetricsTable CourierBold = Parse(CourierBoldData);
    private static readonly MetricsTable CourierBoldOblique = Parse(CourierBoldObliqueData);
    private static readonly MetricsTable CourierOblique = Parse(CourierObliqueData);
    private static readonly MetricsTable Helvetica = Parse(HelveticaData);
    private static readonly MetricsTable HelveticaBold = Parse(HelveticaBoldData);
    private static readonly MetricsTable TimesBold = Parse(TimesBoldData);
    private static readonly MetricsTable TimesBoldItalic = Parse(TimesBoldItalicData);
    private static readonly MetricsTable TimesItalic = Parse(TimesItalicData);
    private static readonly MetricsTable TimesRoman = Parse(TimesRomanData);
    private static readonly MetricsTable Symbol = Parse(SymbolData, SymbolCodeData);
    private static readonly MetricsTable ZapfDingbats =
        Parse(ZapfDingbatsData, ZapfDingbatsCodeData);

    public static bool TryGetWidth(
        string fontName,
        byte characterCode,
        string encoding,
        string decodedText,
        string? glyphName,
        out double width)
    {
        width = 0;
        MetricsTable? table = Resolve(fontName);
        if (table is null)
            return false;

        if (!string.IsNullOrEmpty(glyphName) &&
            table.ByGlyphName.TryGetValue(glyphName, out ushort namedWidth))
        {
            width = namedWidth;
            return true;
        }

        if ((encoding is "Symbol" or "ZapfDingbats") &&
            table.ByCharacterCode.TryGetValue(characterCode, out ushort codeWidth))
        {
            width = codeWidth;
            return true;
        }

        if (table.ByUnicode.TryGetValue(decodedText, out ushort unicodeWidth))
        {
            width = unicodeWidth;
            return true;
        }

        return false;
    }

    private static MetricsTable? Resolve(string fontName)
    {
        int subset = fontName.IndexOf('+');
        if (subset == 6)
            fontName = fontName[7..];
        return fontName switch
        {
            "Courier" => Courier,
            "Courier-Bold" => CourierBold,
            "Courier-BoldOblique" => CourierBoldOblique,
            "Courier-Oblique" => CourierOblique,
            "Helvetica" or "Helvetica-Oblique" => Helvetica,
            "Helvetica-Bold" or "Helvetica-BoldOblique" => HelveticaBold,
            "Times-Bold" => TimesBold,
            "Times-BoldItalic" => TimesBoldItalic,
            "Times-Italic" => TimesItalic,
            "Times-Roman" => TimesRoman,
            "Symbol" => Symbol,
            "ZapfDingbats" => ZapfDingbats,
            _ => null
        };
    }

    private static MetricsTable Parse(string data, string? codeData = null)
    {
        var byGlyphName = new Dictionary<string, ushort>(StringComparer.Ordinal);
        var byUnicode = new Dictionary<string, ushort>(StringComparer.Ordinal);
        foreach (string line in data.Split(
                     '\n',
                     StringSplitOptions.RemoveEmptyEntries))
        {
            int first = line.IndexOf(',');
            int second = first < 0 ? -1 : line[(first + 1)..].IndexOf(',');
            if (first <= 0 || second < 0)
                continue;
            second += first + 1;
            string glyphName = line[..first];
            if (!ushort.TryParse(
                    line.AsSpan(first + 1, second - first - 1),
                    NumberStyles.None,
                    CultureInfo.InvariantCulture,
                    out ushort width))
            {
                continue;
            }
            byGlyphName.TryAdd(glyphName, width);
            string unicodeHex = line[(second + 1)..];
            if (unicodeHex.Length == 0)
                continue;
            var unicode = new StringBuilder();
            foreach (string scalarText in unicodeHex.Split('.'))
            {
                if (int.TryParse(
                        scalarText,
                        NumberStyles.HexNumber,
                        CultureInfo.InvariantCulture,
                        out int scalar) &&
                    Rune.TryCreate(scalar, out Rune rune))
                {
                    unicode.Append(rune);
                }
            }
            if (unicode.Length > 0)
                byUnicode.TryAdd(unicode.ToString(), width);
        }

        var byCharacterCode = new Dictionary<byte, ushort>();
        if (codeData is not null)
        {
            foreach (string line in codeData.Split(
                         '\n',
                         StringSplitOptions.RemoveEmptyEntries))
            {
                int separator = line.IndexOf(',');
                if (separator <= 0 ||
                    !byte.TryParse(
                        line.AsSpan(0, separator),
                        NumberStyles.HexNumber,
                        CultureInfo.InvariantCulture,
                        out byte code) ||
                    !ushort.TryParse(
                        line.AsSpan(separator + 1),
                        NumberStyles.None,
                        CultureInfo.InvariantCulture,
                        out ushort width))
                {
                    continue;
                }
                byCharacterCode.TryAdd(code, width);
            }
        }

        return new MetricsTable(byGlyphName, byUnicode, byCharacterCode);
    }

    private sealed record MetricsTable(
        IReadOnlyDictionary<string, ushort> ByGlyphName,
        IReadOnlyDictionary<string, ushort> ByUnicode,
        IReadOnlyDictionary<byte, ushort> ByCharacterCode);

